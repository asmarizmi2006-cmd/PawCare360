    // Passive display helpers
    public void setRows(java.util.List<Object[]> rows)
    {
        DefaultTableModel model = (DefaultTableModel) tblStaff.getModel();
        model.setRowCount(0);
        for (Object[] row : rows)
        {
            model.addRow(row);
        }
    }

    public void setStats(long total, long active, long onLeave, long inactive)
    {
        lblTotalCount.setText(String.valueOf(total));
        lblActiveCount.setText(String.valueOf(active));
        lblOnLeaveCount.setText(String.valueOf(onLeave));
        lblInactiveCount.setText(String.valueOf(inactive));
    }

    public void fillForm(String name, String role, String phone, String email,
            String specialization, String hireDate, String status)
    {
        txtFullName.setText(name);
        cmbRole.setSelectedItem(role);
        txtPhone.setText(phone);
        txtEmail.setText(email);
        txtSpecialization.setText(specialization);
        txtHireDate.setText(hireDate);
        cmbStatus.setSelectedItem(status);
    }

    public void clearForm()
    {
        txtFullName.setText("");
        txtPhone.setText("");
        txtEmail.setText("");
        txtSpecialization.setText("");
        txtHireDate.setText("");
        cmbRole.setSelectedIndex(0);
        cmbStatus.setSelectedIndex(0);
        tblStaff.clearSelection();
    }

    public String cellText(int row, int col)
    {
        Object v = tblStaff.getValueAt(row, col);
        return v == null ? "" : v.toString();
    }


