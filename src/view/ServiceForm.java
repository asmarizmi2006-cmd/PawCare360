    // Cells not editable
    private void readOnlyTable()
    {
        DefaultTableModel old = (DefaultTableModel) tblServices.getModel();
        String[] cols = new String[old.getColumnCount()];
        for (int i = 0; i < cols.length; i++)
        {
            cols[i] = old.getColumnName(i);
        }
        tblServices.setModel(new DefaultTableModel(new Object[0][], cols)
        {
            @Override
            public boolean isCellEditable(int row, int column)
            {
                return false;
            }
        });
    }

