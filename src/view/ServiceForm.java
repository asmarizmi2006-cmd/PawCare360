    // Passive display helpers
    public void setRows(java.util.List<Object[]> rows)
    {
        DefaultTableModel model = (DefaultTableModel) tblServices.getModel();
        model.setRowCount(0);
        for (Object[] row : rows)
        {
            model.addRow(row);
        }
    }

    public void setStats(long total, long active, long inactive, long categories)
    {
        lblTotalCount.setText(String.valueOf(total));
        lblActiveCount.setText(String.valueOf(active));
        lblInactiveCount.setText(String.valueOf(inactive));
        lblCategoriesCount.setText(String.valueOf(categories));
    }

    public void fillForm(String name, String category, String price, String duration,
            String description, String status)
    {
        txtServiceName.setText(name);
        txtCategory.setText(category);
        txtPrice.setText(price);
        txtDuartion.setText(duration);
        txtDescription.setText(description);
        cmbStatus.setSelectedItem(status);
    }

    public void clearForm()
    {
        fillForm("", "", "", "", "", "Active");
        tblServices.clearSelection();
    }

    public String cellText(int row, int col)
    {
        Object v = tblServices.getValueAt(row, col);
        return v == null ? "" : v.toString();
    }


